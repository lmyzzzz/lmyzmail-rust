import pytest

from lmyzmail_blackbox.errors import HarnessError
from lmyzmail_blackbox.sql_fixture import (
    extract_oracle_outbound_queue_compatibility,
    mysql_fixture_to_postgres,
    normalize_postgres_schema_dump,
)


def test_longtext_is_translated_by_mysql_to_postgres_dialect() -> None:
    source = """
    CREATE TABLE messages (
        id BIGINT PRIMARY KEY,
        body LONGTEXT NOT NULL,
        note VARCHAR(255)
    );
    """

    translated = mysql_fixture_to_postgres(source)

    assert "LONGTEXT" not in translated.upper()
    assert "body TEXT NOT NULL" in translated
    assert "note VARCHAR(255)" in translated


def test_longtext_text_inside_literal_is_not_rewritten() -> None:
    source = "INSERT INTO messages (id, body) VALUES (1, 'LONGTEXT is data');"

    translated = mysql_fixture_to_postgres(source)

    assert "'LONGTEXT is data'" in translated


def test_real_oracle_hybrid_ddl_translates_longtext_without_losing_constraints() -> None:
    source = """
    CREATE TABLE outbound_mail_queue (
        max_retries INTEGER NOT NULL,
        retry_count INTEGER NOT NULL,
        sent_subdirectory INTEGER,
        created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        next_retry_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
        status VARCHAR(20) NOT NULL CHECK (
            status IN ('PENDING', 'PROCESSING', 'SENT', 'PARTIAL_SUCCESS',
                       'FAILED', 'CANCELLED')
        ),
        attachments_json LONGTEXT,
        body_html LONGTEXT,
        body_text LONGTEXT,
        recipients_json TEXT NOT NULL,
        sender_address VARCHAR(255) NOT NULL,
        PRIMARY KEY (id)
    );
    """

    translated = mysql_fixture_to_postgres(source)

    assert "LONGTEXT" not in translated.upper()
    assert translated.upper().count(" TEXT") == 4
    assert "GENERATED BY DEFAULT AS IDENTITY" in translated.upper()
    assert "TIMESTAMPTZ(6) NOT NULL" in translated.upper()
    assert "CHECK" in translated.upper()


def test_extract_real_oracle_longtext_failure_and_indexes() -> None:
    create = (
        "create table outbound_mail_queue (id bigint generated by default as identity, "
        "attachments_json LONGTEXT, body_html LONGTEXT, body_text LONGTEXT, "
        "primary key (id))"
    )
    indexes = (
        "create index idx_queue_status_retry on outbound_mail_queue (status, next_retry_at)",
        "create index idx_queue_sender on outbound_mail_queue (sender_address)",
        "create index idx_queue_created on outbound_mail_queue (created_at)",
        "create index idx_queue_sent_file on outbound_mail_queue (sent_file_name)",
    )
    failures = [create, *indexes, create]
    log_text = "\n".join(
        f'Error executing DDL "{statement}" via JDBC [ERROR]' for statement in failures
    )
    log_text += '\nCaused by: ERROR: type "longtext" does not exist\n'

    compatibility = extract_oracle_outbound_queue_compatibility(log_text)

    assert compatibility.source_sql.count("create table") == 1
    assert compatibility.source_sql.count("create index") == 4
    assert "LONGTEXT" not in compatibility.postgres_sql.upper()
    assert "NULLS FIRST" not in compatibility.postgres_sql.upper()
    assert "NULLS LAST" not in compatibility.postgres_sql.upper()
    assert len(compatibility.postgres_statements) == 5


def test_extract_oracle_longtext_failure_rejects_incomplete_index_contract() -> None:
    log_text = "\n".join(
        (
            'Error executing DDL "create table outbound_mail_queue '
            '(attachments_json LONGTEXT, body_html LONGTEXT, body_text LONGTEXT)" '
            "via JDBC",
            'Caused by: ERROR: type "longtext" does not exist',
        )
    )

    with pytest.raises(HarnessError, match="frozen contract"):
        extract_oracle_outbound_queue_compatibility(log_text)


def test_pg_dump_normalizer_removes_only_random_restrict_tokens() -> None:
    source = (
        b"header\n\\restrict random-token\nCREATE TABLE keep_me ();\n"
        b"\\unrestrict another-token\nfooter\n"
    )

    assert normalize_postgres_schema_dump(source) == (b"header\nCREATE TABLE keep_me ();\nfooter\n")
