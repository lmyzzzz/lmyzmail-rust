CREATE TABLE outbound_mail_queue (
  max_retries INT NOT NULL,
  retry_count INT NOT NULL,
  sent_subdirectory INT,
  created_at TIMESTAMPTZ(6) NOT NULL,
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  next_retry_at TIMESTAMPTZ(6) NOT NULL,
  processing_started_at TIMESTAMPTZ(6),
  sent_at TIMESTAMPTZ(6),
  updated_at TIMESTAMPTZ(6) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'PARTIAL_SUCCESS', 'FAILED', 'CANCELLED')),
  processor_id VARCHAR(100),
  subject VARCHAR(1000),
  attachments_json TEXT,
  body_html TEXT,
  body_text TEXT,
  failed_domains_json TEXT,
  last_error TEXT,
  message_id VARCHAR(255),
  recipients_json TEXT NOT NULL,
  sender_address VARCHAR(255) NOT NULL,
  sent_domains_json TEXT,
  sent_file_name VARCHAR(255),
  PRIMARY KEY (id)
);
CREATE INDEX idx_queue_status_retry ON outbound_mail_queue(status, next_retry_at);
CREATE INDEX idx_queue_sender ON outbound_mail_queue(sender_address);
CREATE INDEX idx_queue_created ON outbound_mail_queue(created_at);
CREATE INDEX idx_queue_sent_file ON outbound_mail_queue(sent_file_name);
