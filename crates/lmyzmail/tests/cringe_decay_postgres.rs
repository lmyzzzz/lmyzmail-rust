const DECAY_UPDATE_MARKER: &[u8] = b"UPDATE skibidi_cringe_ip";
const DECAY_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_cringe_decay_commit_reconciliation";
const COMMIT_MARKER: &[u8] = b"COMMIT\0";

static POSTGRES_START_LOCK: Mutex<()> = Mutex::new(());

const DECAY_DDL: &str = r#"
CREATE TABLE skibidi_cringe_ip (
    ip_address varchar(45) PRIMARY KEY,
    total_score integer NOT NULL,
    current_score integer NOT NULL,
    last_decay_at timestamp(6) with time zone
);
CREATE TABLE skibidi_cringe_ip_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp timestamp(6) with time zone NOT NULL
);
"#;

struct CommitResponseLossProxy {
    port: u16,
    commit_seen: Arc<AtomicBool>,
    reconciliation_seen: Arc<AtomicBool>,
    stop: CancellationToken,
    task: Option<JoinHandle<()>>,
}

impl CommitResponseLossProxy {
    async fn start(upstream_port: u16) -> Self {
        Self::start_with_reconciliation_stall(upstream_port, false).await
    }

    async fn start_stalling_reconciliation(upstream_port: u16) -> Self {
        Self::start_with_reconciliation_stall(upstream_port, true).await
    }

    async fn start_with_reconciliation_stall(
        upstream_port: u16,
        stall_reconciliation: bool,
    ) -> Self {
        let listener = TokioTcpListener::bind(("127.0.0.1", 0)).await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let commit_seen = Arc::new(AtomicBool::new(false));
        let reconciliation_seen = Arc::new(AtomicBool::new(false));
        let stop = CancellationToken::new();
        let task_commit_seen = Arc::clone(&commit_seen);
        let task_reconciliation_seen = Arc::clone(&reconciliation_seen);
        let task_stop = stop.clone();
        let task = tokio::spawn(async move {
            let mut connections = tokio::task::JoinSet::new();
            loop {
                let accepted = tokio::select! {
                    biased;
                    () = task_stop.cancelled() => break,
                    accepted = listener.accept() => accepted,
                };
                let Ok((client, _)) = accepted else {
                    break;
                };
                let Ok(server) = TcpStream::connect(("127.0.0.1", upstream_port)).await else {
                    continue;
                };
                let shared_commit_seen = Arc::clone(&task_commit_seen);
                let shared_reconciliation_seen = Arc::clone(&task_reconciliation_seen);
                let connection_stop = task_stop.clone();
                connections.spawn(async move {
                    let (mut client_read, mut client_write) = client.into_split();
                    let (mut server_read, mut server_write) = server.into_split();
                    let mutation_seen = Arc::new(AtomicBool::new(false));
                    let relay_mutation_seen = Arc::clone(&mutation_seen);
                    let response_mutation_seen = Arc::clone(&mutation_seen);
                    let hide_commit_response = CancellationToken::new();
                    let relay_hide_commit_response = hide_commit_response.clone();
                    let hold_reconciliation_response = CancellationToken::new();
                    let relay_hold_reconciliation_response =
                        hold_reconciliation_response.clone();
                    let relay_stop = connection_stop.clone();
                    let response_stop = connection_stop;
                    let client_to_server = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        let mut marker_tail = Vec::new();
                        loop {
                            let count = tokio::select! {
                                biased;
                                () = relay_stop.cancelled() => return Ok::<(), std::io::Error>(()),
                                count = client_read.read(&mut buffer) => count?,
                            };
                            if count == 0 {
                                break;
                            }
                            marker_tail.extend_from_slice(&buffer[..count]);
                            if contains_marker(&marker_tail, DECAY_UPDATE_MARKER) {
                                relay_mutation_seen.store(true, Ordering::SeqCst);
                            }
                            if contains_marker(&marker_tail, DECAY_RECONCILIATION_MARKER) {
                                shared_reconciliation_seen.store(true, Ordering::SeqCst);
                                if stall_reconciliation {
                                    relay_hold_reconciliation_response.cancel();
                                }
                            }
                            let hide_commit = relay_mutation_seen.load(Ordering::SeqCst)
                                && contains_marker(&marker_tail, COMMIT_MARKER)
                                && !shared_commit_seen.load(Ordering::SeqCst);
                            retain_marker_overlap(&mut marker_tail);
                            server_write.write_all(&buffer[..count]).await?;
                            if hide_commit {
                                server_write.shutdown().await?;
                                shared_commit_seen.store(true, Ordering::SeqCst);
                                relay_hide_commit_response.cancel();
                                return Ok::<(), std::io::Error>(());
                            }
                        }
                        server_write.shutdown().await
                    };
                    let server_to_client = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        loop {
                            let count = tokio::select! {
                                biased;
                                () = response_stop.cancelled() => return Ok::<(), std::io::Error>(()),
                                () = hide_commit_response.cancelled(),
                                    if response_mutation_seen.load(Ordering::SeqCst) => {
                                        client_write.shutdown().await?;
                                        while server_read.read(&mut buffer).await? != 0 {}
                                        return Ok::<(), std::io::Error>(());
                                    }
                                () = hold_reconciliation_response.cancelled() => {
                                    response_stop.cancelled().await;
                                    return Ok::<(), std::io::Error>(());
                                }
                                count = server_read.read(&mut buffer) => count?,
                            };
                            if count == 0 {
                                break;
                            }
                            client_write.write_all(&buffer[..count]).await?;
                        }
                        client_write.shutdown().await
                    };
                    let _ = tokio::join!(client_to_server, server_to_client);
                });
            }
            while connections.join_next().await.is_some() {}
        });
        Self {
            port,
            commit_seen,
            reconciliation_seen,
            stop,
            task: Some(task),
        }
    }
}

impl Drop for CommitResponseLossProxy {
    fn drop(&mut self) {
        self.stop.cancel();
        if let Some(task) = self.task.take() {
            task.abort();
        }
    }
}

fn contains_marker(bytes: &[u8], marker: &[u8]) -> bool {
    bytes.windows(marker.len()).any(|window| window == marker)
}

fn retain_marker_overlap(bytes: &mut Vec<u8>) {
    let retained = DECAY_UPDATE_MARKER
        .len()
        .max(DECAY_RECONCILIATION_MARKER.len())
        .max(COMMIT_MARKER.len())
        .saturating_sub(1);
    if bytes.len() > retained {
        bytes.drain(..bytes.len() - retained);
    }
}

struct PostgresProcess {
    child: Child,
    directory: PathBuf,
    port: u16,
}

impl PostgresProcess {
    fn start() -> Self {
        let _start_guard = POSTGRES_START_LOCK
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let listener = TcpListener::bind(("127.0.0.1", 0)).unwrap();
        let port = listener.local_addr().unwrap().port();
        drop(listener);

        let repository = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(Path::parent)
            .unwrap();
        let root = repository.join(".blackbox/runtime/postgres-root");
        let binary_directory = root.join("usr/lib/postgresql/16/bin");
        let library_directory = root.join("usr/lib/x86_64-linux-gnu");
        let initdb = binary_directory.join("initdb");
        let postgres = binary_directory.join("postgres");
        let pg_isready = binary_directory.join("pg_isready");
        assert!(initdb.is_file(), "PostgreSQL initdb missing");
        assert!(postgres.is_file(), "PostgreSQL server missing");

        let nonce = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let directory = std::env::temp_dir().join(format!(
            "lmyzmail-postgres-cringe-decay-{}-{nonce}",
            std::process::id()
        ));
        let data_directory = directory.join("data");
        let socket_directory = directory.join("socket");
        fs::create_dir_all(&socket_directory).unwrap();

        let initialized = Command::new(initdb)
            .args([
                "--pgdata",
                data_directory.to_str().unwrap(),
                "--username=lmyzmail_test",
                "--auth=trust",
                "--encoding=UTF8",
                "--no-locale",
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", &library_directory)
            .status()
            .unwrap();
        assert!(initialized.success(), "PostgreSQL initdb failed");

        let child = Command::new(postgres)
            .args([
                "-D",
                data_directory.to_str().unwrap(),
                "-h",
                "127.0.0.1",
                "-p",
                &port.to_string(),
                "-k",
                socket_directory.to_str().unwrap(),
                "-F",
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", &library_directory)
            .spawn()
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            let ready = Command::new(&pg_isready)
                .args([
                    "--host=127.0.0.1",
                    &format!("--port={port}"),
                    "--username=lmyzmail_test",
                    "--dbname=postgres",
                    "--timeout=1",
                ])
                .stdin(Stdio::null())
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .env("LD_LIBRARY_PATH", &library_directory)
                .status()
                .unwrap();
            if ready.success() {
                break;
            }
            assert!(Instant::now() < deadline, "PostgreSQL did not start");
            std::thread::sleep(Duration::from_millis(20));
        }
        Self {
            child,
            directory,
            port,
        }
    }
}

impl Drop for PostgresProcess {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        if self
            .directory
            .file_name()
            .and_then(|value| value.to_str())
            .is_some_and(|value| value.starts_with("lmyzmail-postgres-cringe-decay-"))
        {
            let _ = fs::remove_dir_all(&self.directory);
        }
    }
}

fn configuration(port: u16) -> RuntimeConfig {
    let mut properties = Properties::default();
    for (key, value) in [
        ("lmyzmail.postgres.host", "127.0.0.1".to_owned()),
        ("lmyzmail.postgres.port", port.to_string()),
        ("lmyzmail.postgres.database", "postgres".to_owned()),
        ("lmyzmail.postgres.username", "lmyzmail_test".to_owned()),
        ("lmyzmail.postgres.password", String::new()),
        ("lmyzmail.postgres.pool.max-size", "8".to_owned()),
    ] {
        properties.insert(key.to_owned(), value).unwrap();
    }
    RuntimeConfig::from_properties(properties).unwrap()
}

async fn setup() -> (PostgresProcess, deadpool_postgres::Pool, CringeService) {
    let postgres = PostgresProcess::start();
    let pool = database::create_pool(&configuration(postgres.port)).unwrap();
    let client = pool.get().await.unwrap();
    client.batch_execute(DECAY_DDL).await.unwrap();
    drop(client);
    let service = CringeService::new(pool.clone());
    (postgres, pool, service)
}

async fn seed_oracle_rows(pool: &deadpool_postgres::Pool) {
    let client = pool.get().await.unwrap();
    client
        .batch_execute(
            r#"
INSERT INTO skibidi_cringe_ip VALUES
('203.0.113.10',100,47,'2024-01-01T00:00:00Z'),
('203.0.113.11',40,6,'2024-01-01T00:00:00Z'),
('198.51.100.12',31,31,NULL),
('198.51.100.13',50,0,'2024-01-02T00:00:00Z'),
('198.51.100.14',52,52,'2099-01-01T00:00:00Z');
"#,
        )
        .await
        .unwrap();
}

#[tokio::test]
async fn oracle_boundaries_cleanup_and_zero_amount_are_preserved() {
    let (_postgres, pool, service) = setup().await;
    seed_oracle_rows(&pool).await;
    let cancellation = CancellationToken::new();
    assert_eq!(
        service
            .perform_score_decay(Duration::from_secs(86_400), 10, &cancellation)
            .await
            .unwrap(),
        3
    );
    assert_eq!(
        service
            .perform_score_decay(Duration::from_secs(86_400), 10, &cancellation)
            .await
            .unwrap(),
        0
    );
    assert_eq!(
        service
            .perform_score_decay(Duration::from_secs(86_400), 0, &cancellation)
            .await
            .unwrap(),
        0
    );
    assert_eq!(
        service
            .current_score("203.0.113.10", &cancellation)
            .await
            .unwrap(),
        Some(37)
    );
    let client = pool.get().await.unwrap();
    let rows = client
        .query(
            "SELECT ip_address,current_score,last_decay_at FROM skibidi_cringe_ip ORDER BY ip_address",
            &[],
        )
        .await
        .unwrap();
    let scores = rows
        .iter()
        .map(|row| (row.get::<_, String>(0), row.get::<_, i32>(1)))
        .collect::<Vec<_>>();
    assert_eq!(
        scores,
        [
            ("198.51.100.12".into(), 21),
            ("198.51.100.13".into(), 0),
            ("198.51.100.14".into(), 52),
            ("203.0.113.10".into(), 37),
            ("203.0.113.11".into(), 0),
        ]
    );
    assert!(
        rows[0]
            .get::<_, Option<chrono::DateTime<chrono::Utc>>>(2)
            .is_some()
    );
    assert_eq!(
        rows[1]
            .get::<_, chrono::DateTime<chrono::Utc>>(2)
            .to_rfc3339(),
        "2024-01-02T00:00:00+00:00"
    );
    assert_eq!(
        rows[2]
            .get::<_, chrono::DateTime<chrono::Utc>>(2)
            .to_rfc3339(),
        "2099-01-01T00:00:00+00:00"
    );
    client
        .batch_execute(
            "INSERT INTO skibidi_cringe_ip_activity(timestamp) VALUES \
             ('2020-01-01T00:00:00Z'),(CURRENT_TIMESTAMP)",
        )
        .await
        .unwrap();
    drop(client);
    assert_eq!(
        service
            .cleanup_old_activities(360, &cancellation)
            .await
            .unwrap(),
        1
    );
}

#[tokio::test]
async fn reconciliation_xid_excludes_same_timestamp_from_another_transaction() {
    let (_postgres, pool, _service) = setup().await;
    let mut client = pool.get().await.unwrap();
    client
        .batch_execute(
            "INSERT INTO skibidi_cringe_ip VALUES \
             ('203.0.113.30',10,10,NULL),('203.0.113.31',10,10,NULL)",
        )
        .await
        .unwrap();
    let transaction = client.transaction().await.unwrap();
    let transaction_id = transaction
        .query_one("SELECT pg_current_xact_id()::xid::text", &[])
        .await
        .unwrap()
        .get::<_, String>(0);
    transaction
        .execute(
            "UPDATE skibidi_cringe_ip SET last_decay_at = \
             TIMESTAMPTZ '2026-08-09 00:00:00.123456Z' WHERE ip_address = '203.0.113.30'",
            &[],
        )
        .await
        .unwrap();
    transaction.commit().await.unwrap();

    client
        .execute(
            "UPDATE skibidi_cringe_ip SET last_decay_at = \
             TIMESTAMPTZ '2026-08-09 00:00:00.123456Z' WHERE ip_address = '203.0.113.31'",
            &[],
        )
        .await
        .unwrap();
    let timestamp_count = client
        .query_one(
            "SELECT COUNT(*) FROM skibidi_cringe_ip WHERE last_decay_at = \
             TIMESTAMPTZ '2026-08-09 00:00:00.123456Z'",
            &[],
        )
        .await
        .unwrap()
        .get::<_, i64>(0);
    let transaction_count = client
        .query_one(
            "SELECT COUNT(*) FROM skibidi_cringe_ip WHERE last_decay_at = \
             TIMESTAMPTZ '2026-08-09 00:00:00.123456Z' AND xmin::text = $1",
            &[&transaction_id],
        )
        .await
        .unwrap()
        .get::<_, i64>(0);
    assert_eq!(timestamp_count, 2);
    assert_eq!(transaction_count, 1);
}

#[tokio::test]
async fn concurrent_decay_is_serialized_and_pre_cancel_has_no_side_effect() {
    let (_postgres, pool, service) = setup().await;
    seed_oracle_rows(&pool).await;
    let first = service.clone();
    let second = service.clone();
    let first_task = tokio::spawn(async move {
        first
            .perform_score_decay(Duration::from_secs(86_400), 10, &CancellationToken::new())
            .await
    });
    let second_task = tokio::spawn(async move {
        second
            .perform_score_decay(Duration::from_secs(86_400), 10, &CancellationToken::new())
            .await
    });
    let total = first_task.await.unwrap().unwrap() + second_task.await.unwrap().unwrap();
    assert_eq!(total, 3);

    let cancelled = CancellationToken::new();
    cancelled.cancel();
    assert!(matches!(
        service
            .perform_score_decay(Duration::from_secs(1), 10, &cancelled)
            .await,
        Err(CringeError::Cancelled)
    ));
    let client = pool.get().await.unwrap();
    assert_eq!(
        client
            .query_one(
                "SELECT current_score FROM skibidi_cringe_ip WHERE ip_address='203.0.113.10'",
                &[],
            )
            .await
            .unwrap()
            .get::<_, i32>(0),
        37
    );
}

#[tokio::test]
async fn lost_commit_response_is_confirmed_without_reapplying_decay() {
    let postgres = PostgresProcess::start();
    let direct_pool = database::create_pool(&configuration(postgres.port)).unwrap();
    let client = direct_pool.get().await.unwrap();
    client.batch_execute(DECAY_DDL).await.unwrap();
    drop(client);
    seed_oracle_rows(&direct_pool).await;

    let proxy = CommitResponseLossProxy::start(postgres.port).await;
    let proxy_pool = database::create_pool(&configuration(proxy.port)).unwrap();
    let service = CringeService::new(proxy_pool);
    let affected = timeout(
        Duration::from_secs(15),
        service.perform_score_decay(Duration::from_secs(86_400), 10, &CancellationToken::new()),
    )
    .await
    .expect("decay commit reconciliation exceeded its outer bound")
    .unwrap();
    assert_eq!(affected, 3);
    assert!(proxy.commit_seen.load(Ordering::SeqCst));
    assert!(proxy.reconciliation_seen.load(Ordering::SeqCst));
    let client = direct_pool.get().await.unwrap();
    assert_eq!(
        client
            .query_one(
                "SELECT current_score FROM skibidi_cringe_ip WHERE ip_address='203.0.113.10'",
                &[],
            )
            .await
            .unwrap()
            .get::<_, i32>(0),
        37
    );
}

#[tokio::test]
async fn cancellation_during_commit_reconciliation_is_bounded_and_unknown() {
    let postgres = PostgresProcess::start();
    let direct_pool = database::create_pool(&configuration(postgres.port)).unwrap();
    let client = direct_pool.get().await.unwrap();
    client.batch_execute(DECAY_DDL).await.unwrap();
    drop(client);
    seed_oracle_rows(&direct_pool).await;

    let proxy = CommitResponseLossProxy::start_stalling_reconciliation(postgres.port).await;
    let proxy_pool = database::create_pool(&configuration(proxy.port)).unwrap();
    let service = CringeService::new(proxy_pool);
    let cancellation = CancellationToken::new();
    let task_cancellation = cancellation.clone();
    let task = tokio::spawn(async move {
        service
            .perform_score_decay(Duration::from_secs(86_400), 10, &task_cancellation)
            .await
    });
    timeout(Duration::from_secs(3), async {
        while !proxy.reconciliation_seen.load(Ordering::SeqCst) {
            tokio::task::yield_now().await;
        }
    })
    .await
    .expect("decay reconciliation did not start");
    cancellation.cancel();
    let result = timeout(Duration::from_secs(4), task)
        .await
        .expect("cancelled reconciliation exceeded its drain bound")
        .unwrap();
    assert!(matches!(result, Err(CringeError::OutcomeUnknown)));

    let client = direct_pool.get().await.unwrap();
    assert_eq!(
        client
            .query_one(
                "SELECT current_score FROM skibidi_cringe_ip WHERE ip_address='203.0.113.10'",
                &[],
            )
            .await
            .unwrap()
            .get::<_, i32>(0),
        37
    );
}
