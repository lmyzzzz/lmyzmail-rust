fn v2_mailbox_path(address: &str) -> PathBuf {
    let normalized = address.trim().to_lowercase();
    let mut path = PathBuf::from("v2");
    for chunk in normalized.as_bytes().chunks(120) {
        let encoded = chunk
            .iter()
            .map(|byte| format!("{byte:02X}"))
            .collect::<String>();
        path.push(format!("c-{encoded}"));
    }
    path.push(format!("z-{:08X}", normalized.len()));
    path
}

