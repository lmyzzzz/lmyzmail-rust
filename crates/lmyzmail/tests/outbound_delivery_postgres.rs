#[tokio::test]
async fn stale_release_is_fenced_without_counting_a_postgresql_rollback() {
    let process = PostgresProcess::start();
    let pool = database::create_pool(&configuration(process.port())).unwrap();
    let client = pool.get().await.unwrap();
    let legacy_ddl = include_str!("../../../blackbox/fixtures/legacy/postgres-longtext-oracle.sql")
        .replace("LONGTEXT", "TEXT");
    client.batch_execute(&legacy_ddl).await.unwrap();
    drop(client);

    let state = PostgresDeliveryState::new(pool.clone());
    state.initialize_schema().await.unwrap();
    let now = timestamp(1_786_000_000);
    insert_pending(&pool, 4_002, 0, 2, now).await;
    let claim = state
        .claim(4_002, "worker-a:claim-1", now)
        .await
        .unwrap()
        .unwrap();
    assert!(
        state
            .release(&claim, now + chrono::Duration::seconds(1))
            .await
            .unwrap()
    );

    let control_before = database_xact_rollback(&pool).await;
    let mut client = pool.get().await.unwrap();
    client
        .transaction()
        .await
        .unwrap()
        .rollback()
        .await
        .unwrap();
    drop(client);
    let rollbacks_before = database_xact_rollback(&pool).await;
    assert_eq!(
        rollbacks_before,
        control_before + 1,
        "the PostgreSQL rollback counter control must be observable"
    );
    assert!(
        !state
            .release(&claim, now + chrono::Duration::seconds(2))
            .await
            .unwrap()
    );
    let rollbacks_after = database_xact_rollback(&pool).await;
    assert_eq!(
        rollbacks_after, rollbacks_before,
        "routine stale-claim fencing must not increment PostgreSQL xact_rollback"
    );
}

