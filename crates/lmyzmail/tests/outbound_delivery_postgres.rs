struct CancelFailureProxy {
    port: u16,
    mutation_seen: Arc<AtomicBool>,
    mutation_notification: Arc<tokio::sync::Notify>,
    stop_accepting: CancellationToken,
    release_responses: CancellationToken,
    accept_task: Option<JoinHandle<()>>,
}

impl CancelFailureProxy {
    async fn start(upstream_port: u16) -> Self {
        let listener = TokioTcpListener::bind(("127.0.0.1", 0)).await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let mutation_seen = Arc::new(AtomicBool::new(false));
        let mutation_notification = Arc::new(tokio::sync::Notify::new());
        let stop_accepting = CancellationToken::new();
        let release_responses = CancellationToken::new();

        let task_mutation_seen = Arc::clone(&mutation_seen);
        let task_mutation_notification = Arc::clone(&mutation_notification);
        let task_stop_accepting = stop_accepting.clone();
        let task_release_responses = release_responses.clone();
        let accept_task = tokio::spawn(async move {
            loop {
                let accepted = tokio::select! {
                    () = task_stop_accepting.cancelled() => break,
                    accepted = listener.accept() => accepted,
                };
                let Ok((client, _)) = accepted else {
                    break;
                };
                let Ok(server) = TcpStream::connect(("127.0.0.1", upstream_port)).await else {
                    continue;
                };
                let connection_mutation_seen = Arc::clone(&task_mutation_seen);
                let connection_notification = Arc::clone(&task_mutation_notification);
                let connection_release = task_release_responses.clone();
                tokio::spawn(async move {
                    let (mut client_read, mut client_write) = client.into_split();
                    let (mut server_read, mut server_write) = server.into_split();
                    let client_to_server = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        let mut marker_tail = Vec::new();
                        loop {
                            let count = client_read.read(&mut buffer).await?;
                            if count == 0 {
                                break;
                            }
                            marker_tail.extend_from_slice(&buffer[..count]);
                            if marker_tail
                                .windows(CLAIM_MUTATION_MARKER.len())
                                .any(|window| window == CLAIM_MUTATION_MARKER)
                            {
                                connection_mutation_seen.store(true, Ordering::SeqCst);
                                connection_notification.notify_waiters();
                            }
                            let retained = CLAIM_MUTATION_MARKER.len().saturating_sub(1);
                            if marker_tail.len() > retained {
                                marker_tail.drain(..marker_tail.len() - retained);
                            }
                            server_write.write_all(&buffer[..count]).await?;
                        }
                        server_write.shutdown().await
                    };
                    let server_to_client = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        loop {
                            let count = server_read.read(&mut buffer).await?;
                            if count == 0 {
                                break;
                            }
                            if connection_mutation_seen.load(Ordering::SeqCst) {
                                connection_release.cancelled().await;
                            }
                            client_write.write_all(&buffer[..count]).await?;
                        }
                        client_write.shutdown().await
                    };
                    let _ = tokio::join!(client_to_server, server_to_client);
                });
            }
        });

        Self {
            port,
            mutation_seen,
            mutation_notification,
            stop_accepting,
            release_responses,
            accept_task: Some(accept_task),
        }
    }

    fn port(&self) -> u16 {
        self.port
    }

    async fn wait_for_claim_mutation(&self) {
        while !self.mutation_seen.load(Ordering::SeqCst) {
            self.mutation_notification.notified().await;
        }
    }

    async fn refuse_new_connections(&mut self) {
        self.stop_accepting.cancel();
        if let Some(task) = self.accept_task.take() {
            task.await.unwrap();
        }
        assert!(
            TcpStream::connect(("127.0.0.1", self.port)).await.is_err(),
            "proxy port must refuse the fallback CancelRequest connection"
        );
    }
}

impl Drop for CancelFailureProxy {
    fn drop(&mut self) {
        self.stop_accepting.cancel();
        self.release_responses.cancel();
        if let Some(task) = self.accept_task.take() {
            task.abort();
        }
    }
}

struct CommitResponseLossProxy {
    port: u16,
    commit_seen: Arc<AtomicBool>,
    commit_notification: Arc<tokio::sync::Notify>,
    reconciliation_seen: Arc<AtomicBool>,
    reconciliation_notification: Arc<tokio::sync::Notify>,
    release_responses: CancellationToken,
    stop_accepting: CancellationToken,
    accept_task: Option<JoinHandle<()>>,
}

impl CommitResponseLossProxy {
    async fn start(upstream_port: u16) -> Self {
        let listener = TokioTcpListener::bind(("127.0.0.1", 0)).await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let commit_seen = Arc::new(AtomicBool::new(false));
        let commit_notification = Arc::new(tokio::sync::Notify::new());
        let reconciliation_seen = Arc::new(AtomicBool::new(false));
        let reconciliation_notification = Arc::new(tokio::sync::Notify::new());
        let release_responses = CancellationToken::new();
        let stop_accepting = CancellationToken::new();

        let task_commit_seen = Arc::clone(&commit_seen);
        let task_commit_notification = Arc::clone(&commit_notification);
        let task_reconciliation_seen = Arc::clone(&reconciliation_seen);
        let task_reconciliation_notification = Arc::clone(&reconciliation_notification);
        let task_release_responses = release_responses.clone();
        let task_stop_accepting = stop_accepting.clone();
        let accept_task = tokio::spawn(async move {
            loop {
                let accepted = tokio::select! {
                    () = task_stop_accepting.cancelled() => break,
                    accepted = listener.accept() => accepted,
                };
                let Ok((client, _)) = accepted else {
                    break;
                };
                let Ok(server) = TcpStream::connect(("127.0.0.1", upstream_port)).await else {
                    continue;
                };
                let connection_commit_seen = Arc::new(AtomicBool::new(false));
                let connection_queue_insert_seen = Arc::new(AtomicBool::new(false));
                let relay_commit_seen = Arc::clone(&connection_commit_seen);
                let response_commit_seen = Arc::clone(&connection_commit_seen);
                let relay_queue_insert_seen = Arc::clone(&connection_queue_insert_seen);
                let shared_commit_seen = Arc::clone(&task_commit_seen);
                let shared_commit_notification = Arc::clone(&task_commit_notification);
                let shared_reconciliation_seen = Arc::clone(&task_reconciliation_seen);
                let shared_reconciliation_notification =
                    Arc::clone(&task_reconciliation_notification);
                let connection_release = task_release_responses.clone();
                tokio::spawn(async move {
                    let (mut client_read, mut client_write) = client.into_split();
                    let (mut server_read, mut server_write) = server.into_split();
                    let client_to_server = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        let mut marker_tail = Vec::new();
                        loop {
                            let count = client_read.read(&mut buffer).await?;
                            if count == 0 {
                                break;
                            }
                            marker_tail.extend_from_slice(&buffer[..count]);
                            if contains_marker(&marker_tail, QUEUE_INSERT_MARKER) {
                                relay_queue_insert_seen.store(true, Ordering::SeqCst);
                            }
                            if !relay_commit_seen.load(Ordering::SeqCst)
                                && relay_queue_insert_seen.load(Ordering::SeqCst)
                                && contains_marker(&marker_tail, COMMIT_MARKER)
                            {
                                relay_commit_seen.store(true, Ordering::SeqCst);
                                shared_commit_seen.store(true, Ordering::SeqCst);
                                shared_commit_notification.notify_waiters();
                            }
                            if shared_commit_seen.load(Ordering::SeqCst)
                                && contains_marker(&marker_tail, COMMIT_RECONCILIATION_MARKER)
                            {
                                shared_reconciliation_seen.store(true, Ordering::SeqCst);
                                shared_reconciliation_notification.notify_waiters();
                            }
                            retain_marker_overlap(&mut marker_tail);
                            server_write.write_all(&buffer[..count]).await?;
                        }
                        server_write.shutdown().await
                    };
                    let server_to_client = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        loop {
                            let count = server_read.read(&mut buffer).await?;
                            if count == 0 {
                                break;
                            }
                            if response_commit_seen.load(Ordering::SeqCst) {
                                connection_release.cancelled().await;
                            }
                            client_write.write_all(&buffer[..count]).await?;
                        }
                        client_write.shutdown().await
                    };
                    let _ = tokio::join!(client_to_server, server_to_client);
                });
            }
        });

        Self {
            port,
            commit_seen,
            commit_notification,
            reconciliation_seen,
            reconciliation_notification,
            release_responses,
            stop_accepting,
            accept_task: Some(accept_task),
        }
    }

    fn port(&self) -> u16 {
        self.port
    }

    async fn wait_for_commit(&self) {
        while !self.commit_seen.load(Ordering::SeqCst) {
            self.commit_notification.notified().await;
        }
    }

    async fn wait_for_reconciliation(&self) {
        while !self.reconciliation_seen.load(Ordering::SeqCst) {
            self.reconciliation_notification.notified().await;
        }
    }

    fn release_commit_response(&self) {
        self.release_responses.cancel();
    }
}

impl Drop for CommitResponseLossProxy {
    fn drop(&mut self) {
        self.stop_accepting.cancel();
        self.release_responses.cancel();
        if let Some(task) = self.accept_task.take() {
            task.abort();
        }
    }
}

fn contains_marker(bytes: &[u8], marker: &[u8]) -> bool {
    bytes.windows(marker.len()).any(|window| window == marker)
}

fn retain_marker_overlap(bytes: &mut Vec<u8>) {
    let retained = COMMIT_RECONCILIATION_MARKER
        .len()
        .max(QUEUE_INSERT_MARKER.len())
        .max(COMMIT_MARKER.len())
        .saturating_sub(1);
    if bytes.len() > retained {
        bytes.drain(..bytes.len() - retained);
    }
}

struct PostgresProcess {
    child: Child,
    directory: PathBuf,
    port: u16,
    binary_directory: PathBuf,
    library_directory: PathBuf,
    durable: bool,
}

impl PostgresProcess {
    fn start() -> Self {
        Self::start_with_durability(false)
    }

    fn start_persistent() -> Self {
        Self::start_with_durability(true)
    }

    fn start_with_durability(durable: bool) -> Self {
        let _start_guard = FIXTURE_PROCESS_START_LOCK
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let listener = TcpListener::bind(("127.0.0.1", 0)).unwrap();
        let port = listener.local_addr().unwrap().port();
        drop(listener);

        let repository = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(Path::parent)
            .unwrap();
        let root = repository.join(".blackbox/runtime/postgres-root");
        let binary_directory = root.join("usr/lib/postgresql/16/bin");
        let library_directory = root.join("usr/lib/x86_64-linux-gnu");
        let initdb = binary_directory.join("initdb");
        let pg_isready = binary_directory.join("pg_isready");
        assert!(initdb.is_file(), "PostgreSQL initdb missing");
        assert!(
            binary_directory.join("postgres").is_file(),
            "PostgreSQL server missing"
        );
        assert!(pg_isready.is_file(), "PostgreSQL pg_isready missing");
        assert!(library_directory.is_dir());

        let nonce = fixture_nonce();
        let directory = std::env::temp_dir().join(format!(
            "lmyzmail-postgres-delivery-{}-{nonce}",
            std::process::id()
        ));
        let data_directory = directory.join("data");
        let socket_directory = directory.join("socket");
        fs::create_dir_all(&socket_directory).unwrap();

        let initialize = Command::new(initdb)
            .args([
                "--pgdata",
                data_directory.to_str().unwrap(),
                "--username=lmyzmail_test",
                "--auth=trust",
                "--encoding=UTF8",
                "--no-locale",
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", &library_directory)
            .status()
            .unwrap();
        assert!(initialize.success(), "PostgreSQL initdb failed");

        let child = Self::spawn_child(
            &binary_directory,
            &library_directory,
            &directory,
            port,
            durable,
        );
        Self::wait_until_ready(&pg_isready, &library_directory, port);
        Self {
            child,
            directory,
            port,
            binary_directory,
            library_directory,
            durable,
        }
    }

    fn spawn_child(
        binary_directory: &Path,
        library_directory: &Path,
        directory: &Path,
        port: u16,
        durable: bool,
    ) -> Child {
        let data_directory = directory.join("data");
        let socket_directory = directory.join("socket");
        let mut command = Command::new(binary_directory.join("postgres"));
        command.args([
            "-D",
            data_directory.to_str().unwrap(),
            "-h",
            "127.0.0.1",
            "-p",
            &port.to_string(),
            "-k",
            socket_directory.to_str().unwrap(),
        ]);
        if durable {
            command.args([
                "-c",
                "fsync=on",
                "-c",
                "synchronous_commit=on",
                "-c",
                "full_page_writes=on",
            ]);
        } else {
            command.arg("-F");
        }
        command
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", library_directory)
            .spawn()
            .unwrap()
    }

    fn wait_until_ready(pg_isready: &Path, library_directory: &Path, port: u16) {
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            let ready = Command::new(pg_isready)
                .args([
                    "--host=127.0.0.1",
                    &format!("--port={port}"),
                    "--username=lmyzmail_test",
                    "--dbname=postgres",
                    "--timeout=1",
                ])
                .stdin(Stdio::null())
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .env("LD_LIBRARY_PATH", library_directory)
                .status()
                .unwrap();
            if ready.success() {
                break;
            }
            assert!(
                Instant::now() < deadline,
                "PostgreSQL test process did not start"
            );
            std::thread::sleep(Duration::from_millis(20));
        }
    }

    fn port(&self) -> u16 {
        self.port
    }

    fn restart_after_kill(&mut self) {
        let _start_guard = FIXTURE_PROCESS_START_LOCK
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        self.child.kill().unwrap();
        self.child.wait().unwrap();
        self.child = Self::spawn_child(
            &self.binary_directory,
            &self.library_directory,
            &self.directory,
            self.port,
            self.durable,
        );
        Self::wait_until_ready(
            &self.binary_directory.join("pg_isready"),
            &self.library_directory,
            self.port,
        );
    }
}

impl Drop for PostgresProcess {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        if self
            .directory
            .file_name()
            .and_then(|value| value.to_str())
            .is_some_and(|value| value.starts_with("lmyzmail-postgres-delivery-"))
        {
            let _ = fs::remove_dir_all(&self.directory);
        }
    }
}

