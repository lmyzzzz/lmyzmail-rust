const MAILBOX_INSERT_MARKER: &[u8] = b"INSERT INTO mailbox";
const SESSION_INSERT_MARKER: &[u8] = b"INSERT INTO user_session";
const SESSION_DELETE_MARKER: &[u8] = b"DELETE FROM user_session";
const SESSION_LAST_USED_MARKER: &[u8] = b"UPDATE user_session SET last_used_at";
const COMMIT_MARKER: &[u8] = b"COMMIT\0";
const MAILBOX_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_auth_mailbox_commit_reconciliation";
const LOGIN_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_auth_login_commit_reconciliation";
const LOGOUT_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_auth_logout_commit_reconciliation";
const EXPIRED_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_auth_expired_session_commit_reconciliation";
const LAST_USED_RECONCILIATION_MARKER: &[u8] = b"lmyzmail_auth_last_used_commit_reconciliation";
const AUTH_DDL: &str = r#"
CREATE TABLE mailbox (
    created_at timestamp(6) with time zone NOT NULL,
    id bigint generated by default as identity PRIMARY KEY,
    address varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL
);
CREATE TABLE user_session (
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    id bigint generated by default as identity PRIMARY KEY,
    last_used_at timestamp(6) with time zone,
    token_prefix varchar(8),
    created_ip varchar(45),
    token_hash varchar(64) NOT NULL UNIQUE,
    user_agent varchar(500),
    mailbox_address varchar(255) NOT NULL
)
"#;

struct CommitResponseLossProxy {
    port: u16,
    commit_seen: Arc<AtomicBool>,
    commit_notification: Arc<tokio::sync::Notify>,
    reconciliation_seen: Arc<AtomicBool>,
    reconciliation_notification: Arc<tokio::sync::Notify>,
    stop_accepting: CancellationToken,
    accept_task: Option<JoinHandle<()>>,
}

impl CommitResponseLossProxy {
    async fn start(
        upstream_port: u16,
        mutation_marker: &'static [u8],
        reconciliation_marker: &'static [u8],
    ) -> Self {
        let listener = TokioTcpListener::bind(("127.0.0.1", 0)).await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let commit_seen = Arc::new(AtomicBool::new(false));
        let commit_notification = Arc::new(tokio::sync::Notify::new());
        let reconciliation_seen = Arc::new(AtomicBool::new(false));
        let reconciliation_notification = Arc::new(tokio::sync::Notify::new());
        let stop_accepting = CancellationToken::new();

        let task_commit_seen = Arc::clone(&commit_seen);
        let task_commit_notification = Arc::clone(&commit_notification);
        let task_reconciliation_seen = Arc::clone(&reconciliation_seen);
        let task_reconciliation_notification = Arc::clone(&reconciliation_notification);
        let task_stop_accepting = stop_accepting.clone();
        let accept_task = tokio::spawn(async move {
            loop {
                let accepted = tokio::select! {
                    () = task_stop_accepting.cancelled() => break,
                    accepted = listener.accept() => accepted,
                };
                let Ok((client, _)) = accepted else {
                    break;
                };
                let Ok(server) = TcpStream::connect(("127.0.0.1", upstream_port)).await else {
                    continue;
                };
                let connection_mutation_seen = Arc::new(AtomicBool::new(false));
                let relay_mutation_seen = Arc::clone(&connection_mutation_seen);
                let response_mutation_seen = Arc::clone(&connection_mutation_seen);
                let shared_commit_seen = Arc::clone(&task_commit_seen);
                let shared_commit_notification = Arc::clone(&task_commit_notification);
                let shared_reconciliation_seen = Arc::clone(&task_reconciliation_seen);
                let shared_reconciliation_notification =
                    Arc::clone(&task_reconciliation_notification);
                let hide_commit_response = CancellationToken::new();
                let relay_hide_commit_response = hide_commit_response.clone();
                tokio::spawn(async move {
                    let (mut client_read, mut client_write) = client.into_split();
                    let (mut server_read, mut server_write) = server.into_split();
                    let client_to_server = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        let mut marker_tail = Vec::new();
                        loop {
                            let count = client_read.read(&mut buffer).await?;
                            if count == 0 {
                                break;
                            }
                            marker_tail.extend_from_slice(&buffer[..count]);
                            if contains_marker(&marker_tail, mutation_marker) {
                                relay_mutation_seen.store(true, Ordering::SeqCst);
                            }
                            let is_target_commit = relay_mutation_seen.load(Ordering::SeqCst)
                                && contains_marker(&marker_tail, COMMIT_MARKER);
                            if shared_commit_seen.load(Ordering::SeqCst)
                                && contains_marker(&marker_tail, reconciliation_marker)
                            {
                                shared_reconciliation_seen.store(true, Ordering::SeqCst);
                                shared_reconciliation_notification.notify_waiters();
                            }
                            retain_marker_overlap(&mut marker_tail);
                            server_write.write_all(&buffer[..count]).await?;
                            if is_target_commit {
                                server_write.shutdown().await?;
                                shared_commit_seen.store(true, Ordering::SeqCst);
                                shared_commit_notification.notify_waiters();
                                relay_hide_commit_response.cancel();
                                return Ok::<(), std::io::Error>(());
                            }
                        }
                        server_write.shutdown().await
                    };
                    let server_to_client = async {
                        let mut buffer = [0_u8; 8 * 1024];
                        loop {
                            let count = tokio::select! {
                                biased;
                                () = hide_commit_response.cancelled(),
                                    if response_mutation_seen.load(Ordering::SeqCst) => {
                                        client_write.shutdown().await?;
                                        while server_read.read(&mut buffer).await? != 0 {}
                                        return Ok::<(), std::io::Error>(());
                                    }
                                count = server_read.read(&mut buffer) => count?,
                            };
                            if count == 0 {
                                break;
                            }
                            client_write.write_all(&buffer[..count]).await?;
                        }
                        client_write.shutdown().await
                    };
                    let _ = tokio::join!(client_to_server, server_to_client);
                });
            }
        });

        Self {
            port,
            commit_seen,
            commit_notification,
            reconciliation_seen,
            reconciliation_notification,
            stop_accepting,
            accept_task: Some(accept_task),
        }
    }

    fn port(&self) -> u16 {
        self.port
    }

    async fn wait_for_commit(&self) {
        while !self.commit_seen.load(Ordering::SeqCst) {
            self.commit_notification.notified().await;
        }
    }

    async fn wait_for_reconciliation(&self) {
        while !self.reconciliation_seen.load(Ordering::SeqCst) {
            self.reconciliation_notification.notified().await;
        }
    }
}

impl Drop for CommitResponseLossProxy {
    fn drop(&mut self) {
        self.stop_accepting.cancel();
        if let Some(task) = self.accept_task.take() {
            task.abort();
        }
    }
}

fn contains_marker(bytes: &[u8], marker: &[u8]) -> bool {
    bytes.windows(marker.len()).any(|window| window == marker)
}

fn retain_marker_overlap(bytes: &mut Vec<u8>) {
    let retained = MAILBOX_INSERT_MARKER
        .len()
        .max(SESSION_LAST_USED_MARKER.len())
        .max(COMMIT_MARKER.len())
        .max(EXPIRED_RECONCILIATION_MARKER.len())
        .saturating_sub(1);
    if bytes.len() > retained {
        bytes.drain(..bytes.len() - retained);
    }
}

fn token_hash(token: &str) -> String {
    let mut output = String::with_capacity(64);
    for byte in Sha256::digest(token.as_bytes()) {
        use std::fmt::Write as _;
        let _ = write!(output, "{byte:02x}");
    }
    output
}

struct PostgresProcess {
    child: Child,
    directory: PathBuf,
    port: u16,
}

impl PostgresProcess {
    fn start() -> Self {
        let listener = TcpListener::bind(("127.0.0.1", 0)).unwrap();
        let port = listener.local_addr().unwrap().port();
        drop(listener);

        let repository = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(Path::parent)
            .unwrap();
        let root = repository.join(".blackbox/runtime/postgres-root");
        let binary_directory = root.join("usr/lib/postgresql/16/bin");
        let library_directory = root.join("usr/lib/x86_64-linux-gnu");
        let initdb = binary_directory.join("initdb");
        let postgres = binary_directory.join("postgres");
        let pg_isready = binary_directory.join("pg_isready");
        assert!(initdb.is_file(), "PostgreSQL initdb missing");
        assert!(postgres.is_file(), "PostgreSQL server missing");
        assert!(pg_isready.is_file(), "PostgreSQL pg_isready missing");
        assert!(library_directory.is_dir());

        let nonce = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let directory = std::env::temp_dir().join(format!(
            "lmyzmail-postgres-auth-{}-{nonce}",
            std::process::id()
        ));
        let data_directory = directory.join("data");
        let socket_directory = directory.join("socket");
        fs::create_dir_all(&socket_directory).unwrap();

        let initialize = Command::new(initdb)
            .args([
                "--pgdata",
                data_directory.to_str().unwrap(),
                "--username=lmyzmail_test",
                "--auth=trust",
                "--encoding=UTF8",
                "--no-locale",
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", &library_directory)
            .status()
            .unwrap();
        assert!(initialize.success(), "PostgreSQL initdb failed");

        let child = Command::new(postgres)
            .args([
                "-D",
                data_directory.to_str().unwrap(),
                "-h",
                "127.0.0.1",
                "-p",
                &port.to_string(),
                "-k",
                socket_directory.to_str().unwrap(),
                "-F",
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .env("LD_LIBRARY_PATH", &library_directory)
            .spawn()
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            let ready = Command::new(&pg_isready)
                .args([
                    "--host=127.0.0.1",
                    &format!("--port={port}"),
                    "--username=lmyzmail_test",
                    "--dbname=postgres",
                    "--timeout=1",
                ])
                .stdin(Stdio::null())
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .env("LD_LIBRARY_PATH", &library_directory)
                .status()
                .unwrap();
            if ready.success() {
                break;
            }
            assert!(
                Instant::now() < deadline,
                "PostgreSQL test process did not start"
            );
            std::thread::sleep(Duration::from_millis(20));
        }
        Self {
            child,
            directory,
            port,
        }
    }

    fn port(&self) -> u16 {
        self.port
    }
}

impl Drop for PostgresProcess {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        if self
            .directory
            .file_name()
            .and_then(|value| value.to_str())
            .is_some_and(|value| value.starts_with("lmyzmail-postgres-auth-"))
        {
            let _ = fs::remove_dir_all(&self.directory);
        }
    }
}

fn configuration(port: u16) -> RuntimeConfig {
    let mut properties = Properties::default();
    for (key, value) in [
        ("lmyzmail.postgres.host", "127.0.0.1".to_owned()),
        ("lmyzmail.postgres.port", port.to_string()),
        ("lmyzmail.postgres.database", "postgres".to_owned()),
        ("lmyzmail.postgres.username", "lmyzmail_test".to_owned()),
        ("lmyzmail.postgres.password", String::new()),
        ("lmyzmail.postgres.pool.max-size", "4".to_owned()),
        ("lmyzmail.domains.main.domain", "example.test".to_owned()),
        ("lmyzmail.domains.main.receive-enabled", "true".to_owned()),
    ] {
        properties.insert(key.to_owned(), value).unwrap();
    }
    RuntimeConfig::from_properties(properties).unwrap()
}

async fn setup(port: u16) -> (deadpool_postgres::Pool, AuthService) {
    let config = configuration(port);
    let pool = database::create_pool(&config).unwrap();
    let client = pool.get().await.unwrap();
    client.batch_execute(AUTH_DDL).await.unwrap();
    drop(client);
    let service = AuthService::from_config(&config, pool.clone()).unwrap();
    (pool, service)
}

#[tokio::test]
async fn mailbox_creation_reconciles_a_lost_commit_response() {
    let postgres = PostgresProcess::start();
    let direct_config = configuration(postgres.port());
    let direct_pool = database::create_pool(&direct_config).unwrap();
    let client = direct_pool.get().await.unwrap();
    client.batch_execute(AUTH_DDL).await.unwrap();
    drop(client);

    let proxy = CommitResponseLossProxy::start(
        postgres.port(),
        MAILBOX_INSERT_MARKER,
        MAILBOX_RECONCILIATION_MARKER,
    )
    .await;
    let proxied_config = configuration(proxy.port());
    let proxied_pool = database::create_pool(&proxied_config).unwrap();
    let service = AuthService::from_config(&proxied_config, proxied_pool).unwrap();
    let creation = tokio::spawn(async move {
        service
            .create_mailbox_api(
                "reconciled@example.test",
                "ReconciledPass123!",
                "192.0.2.10",
            )
            .await
    });

    tokio::time::timeout(Duration::from_secs(5), proxy.wait_for_commit())
        .await
        .expect("mailbox creation did not issue COMMIT");
    tokio::time::timeout(Duration::from_secs(10), proxy.wait_for_reconciliation())
        .await
        .expect("mailbox creation did not reconcile the lost COMMIT response");
    let created = tokio::time::timeout(Duration::from_secs(5), creation)
        .await
        .expect("mailbox creation did not finish after reconciliation")
        .unwrap()
        .unwrap();

    let client = direct_pool.get().await.unwrap();
    let row = client
        .query_one(
            "SELECT id,address,password_hash FROM mailbox WHERE address=$1",
            &[&"reconciled@example.test"],
        )
        .await
        .unwrap();
    assert_eq!(row.get::<_, i64>(0), created.id);
    assert_eq!(row.get::<_, &str>(1), created.address);
    assert!(bcrypt::verify("ReconciledPass123!", row.get::<_, &str>(2)).unwrap());
}

#[tokio::test]
async fn session_mutations_reconcile_lost_commit_responses() {
    let postgres = PostgresProcess::start();
    let (direct_pool, direct_service) = setup(postgres.port()).await;
    direct_service
        .create_mailbox_api(
            "sessions@example.test",
            "SessionCommitPass123!",
            "192.0.2.20",
        )
        .await
        .unwrap();

    let token = {
        let proxy = CommitResponseLossProxy::start(
            postgres.port(),
            SESSION_INSERT_MARKER,
            LOGIN_RECONCILIATION_MARKER,
        )
        .await;
        let config = configuration(proxy.port());
        let pool = database::create_pool(&config).unwrap();
        let service = AuthService::from_config(&config, pool).unwrap();
        let login = tokio::spawn(async move {
            service
                .login(
                    "sessions@example.test",
                    "SessionCommitPass123!",
                    "192.0.2.21",
                    Some("auth-commit-test"),
                )
                .await
        });
        tokio::time::timeout(Duration::from_secs(5), proxy.wait_for_commit())
            .await
            .expect("login did not issue COMMIT");
        tokio::time::timeout(Duration::from_secs(10), proxy.wait_for_reconciliation())
            .await
            .expect("login did not reconcile the lost COMMIT response");
        let (outcome, response) = tokio::time::timeout(Duration::from_secs(5), login)
            .await
            .expect("login did not finish after reconciliation")
            .unwrap()
            .unwrap();
        assert_eq!(outcome, LoginOutcome::Success);
        response.unwrap().token
    };
    let hash = token_hash(&token);
    let client = direct_pool.get().await.unwrap();
    let before_last_used: chrono::DateTime<chrono::Utc> = client
        .query_one(
            "SELECT last_used_at FROM user_session WHERE token_hash=$1",
            &[&hash],
        )
        .await
        .unwrap()
        .get(0);
    drop(client);
    tokio::time::sleep(Duration::from_millis(2)).await;

    {
        let proxy = CommitResponseLossProxy::start(
            postgres.port(),
            SESSION_LAST_USED_MARKER,
            LAST_USED_RECONCILIATION_MARKER,
        )
        .await;
        let config = configuration(proxy.port());
        let pool = database::create_pool(&config).unwrap();
        let service = AuthService::from_config(&config, pool).unwrap();
        let validation_token = token.clone();
        let validation =
            tokio::spawn(async move { service.validate_token(&validation_token).await });
        tokio::time::timeout(Duration::from_secs(5), proxy.wait_for_commit())
            .await
            .expect("last-used update did not issue COMMIT");
        tokio::time::timeout(Duration::from_secs(10), proxy.wait_for_reconciliation())
            .await
            .expect("last-used update did not reconcile the lost COMMIT response");
        assert_eq!(
            tokio::time::timeout(Duration::from_secs(5), validation)
                .await
                .expect("token validation did not finish after reconciliation")
                .unwrap()
                .unwrap()
                .as_deref(),
            Some("sessions@example.test")
        );
    }
    let client = direct_pool.get().await.unwrap();
    let after_last_used: chrono::DateTime<chrono::Utc> = client
        .query_one(
            "SELECT last_used_at FROM user_session WHERE token_hash=$1",
            &[&hash],
        )
        .await
        .unwrap()
        .get(0);
    assert!(after_last_used > before_last_used);
    drop(client);

    {
        let proxy = CommitResponseLossProxy::start(
            postgres.port(),
            SESSION_DELETE_MARKER,
            LOGOUT_RECONCILIATION_MARKER,
        )
        .await;
        let config = configuration(proxy.port());
        let pool = database::create_pool(&config).unwrap();
        let service = AuthService::from_config(&config, pool).unwrap();
        let logout_token = token.clone();
        let logout = tokio::spawn(async move { service.logout(Some(&logout_token)).await });
        tokio::time::timeout(Duration::from_secs(5), proxy.wait_for_commit())
            .await
            .expect("logout did not issue COMMIT");
        tokio::time::timeout(Duration::from_secs(10), proxy.wait_for_reconciliation())
            .await
            .expect("logout did not reconcile the lost COMMIT response");
        tokio::time::timeout(Duration::from_secs(5), logout)
            .await
            .expect("logout did not finish after reconciliation")
            .unwrap()
            .unwrap();
    }
    let client = direct_pool.get().await.unwrap();
    let count: i64 = client
        .query_one(
            "SELECT count(*) FROM user_session WHERE token_hash=$1",
            &[&hash],
        )
        .await
        .unwrap()
        .get(0);
    assert_eq!(count, 0);

    let expired_token = "expired-session-token";
    let expired_hash = token_hash(expired_token);
    let now = chrono::Utc::now();
    client
        .execute(
            "INSERT INTO user_session
             (mailbox_address,token_hash,token_prefix,created_at,expires_at,last_used_at,created_ip,user_agent)
             VALUES ($1,$2,$3,$4,$5,$4,$6,$7)",
            &[
                &"sessions@example.test",
                &expired_hash,
                &"expired-",
                &(now - chrono::Duration::hours(2)),
                &(now - chrono::Duration::hours(1)),
                &"192.0.2.22",
                &Option::<String>::None,
            ],
        )
        .await
        .unwrap();
    drop(client);

    {
        let proxy = CommitResponseLossProxy::start(
            postgres.port(),
            SESSION_DELETE_MARKER,
            EXPIRED_RECONCILIATION_MARKER,
        )
        .await;
        let config = configuration(proxy.port());
        let pool = database::create_pool(&config).unwrap();
        let service = AuthService::from_config(&config, pool).unwrap();
        let validation = tokio::spawn(async move { service.validate_token(expired_token).await });
        tokio::time::timeout(Duration::from_secs(5), proxy.wait_for_commit())
            .await
            .expect("expired session deletion did not issue COMMIT");
        tokio::time::timeout(Duration::from_secs(10), proxy.wait_for_reconciliation())
            .await
            .expect("expired session deletion did not reconcile the lost COMMIT response");
        assert_eq!(
            tokio::time::timeout(Duration::from_secs(5), validation)
                .await
                .expect("expired token validation did not finish after reconciliation")
                .unwrap()
                .unwrap(),
            None
        );
    }
    let client = direct_pool.get().await.unwrap();
    let count: i64 = client
        .query_one(
            "SELECT count(*) FROM user_session WHERE token_hash=$1",
            &[&expired_hash],
        )
        .await
        .unwrap()
        .get(0);
    assert_eq!(count, 0);
}

#[tokio::test]
async fn concurrent_mailbox_creation_serializes_on_the_address() {
    let postgres = PostgresProcess::start();
    let (pool, first_service) = setup(postgres.port()).await;
    let second_service =
        AuthService::from_config(&configuration(postgres.port()), pool.clone()).unwrap();

    let (first, second) = tokio::join!(
        first_service.create_mailbox_api(
            "single@example.test",
            "FirstConcurrentPass123!",
            "192.0.2.11",
        ),
        second_service.create_mailbox_api(
            "single@example.test",
            "SecondConcurrentPass123!",
            "192.0.2.12",
        )
    );
    let mut created = Vec::new();
    let mut duplicate_errors = 0;
    for result in [first, second] {
        match result {
            Ok(mailbox) => created.push(mailbox),
            Err(AuthError::InvalidInput(message))
                if message == "Mailbox already exists: single@example.test" =>
            {
                duplicate_errors += 1;
            }
            other => panic!("unexpected concurrent creation result: {other:?}"),
        }
    }
    assert_eq!(created.len(), 1);
    assert_eq!(duplicate_errors, 1);

    let client = pool.get().await.unwrap();
    let count: i64 = client
        .query_one(
            "SELECT count(*) FROM mailbox WHERE address=$1",
            &[&"single@example.test"],
        )
        .await
        .unwrap()
        .get(0);
    assert_eq!(count, 1);
}
