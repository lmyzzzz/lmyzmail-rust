fn domains_for_recipients(recipients: &[&str]) -> BTreeMap<String, DomainStatus> {
    let mut grouped = BTreeMap::<String, Vec<String>>::new();
    for recipient in recipients {
        let domain = recipient.rsplit_once('@').unwrap().1.to_owned();
        grouped.entry(domain).or_default().push((*recipient).into());
    }
    grouped
        .into_iter()
        .map(|(domain, recipients)| {
            (
                domain.clone(),
                DomainStatus {
                    domain,
                    status: "PENDING".into(),
                    error: None,
                    recipients,
                    updated_at: Utc::now().to_rfc3339(),
                },
            )
        })
        .collect()
}

