fn nonce() -> u128 {
    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    timestamp ^ u128::from(NONCE_COUNTER.fetch_add(1, Ordering::Relaxed))
}

