struct DropResponseProxy {
    port: u16,
    stop: Arc<AtomicBool>,
    response_dropped: Arc<AtomicBool>,
    connection_count: Arc<AtomicUsize>,
    thread: Option<JoinHandle<()>>,
}

#[derive(Clone, Copy)]
enum DropResponseMode {
    FirstResponse,
    PostgresReadyForQuery,
}

impl DropResponseProxy {
    fn start(upstream_port: u16, request_marker: &'static [u8]) -> Self {
        Self::start_with_mode(
            upstream_port,
            request_marker,
            DropResponseMode::FirstResponse,
        )
    }

    fn start_after_postgres_ready(upstream_port: u16, request_marker: &'static [u8]) -> Self {
        Self::start_with_mode(
            upstream_port,
            request_marker,
            DropResponseMode::PostgresReadyForQuery,
        )
    }

    fn start_with_mode(
        upstream_port: u16,
        request_marker: &'static [u8],
        mode: DropResponseMode,
    ) -> Self {
        let listener = StdTcpListener::bind(("127.0.0.1", 0)).unwrap();
        listener.set_nonblocking(true).unwrap();
        let port = listener.local_addr().unwrap().port();
        let stop = Arc::new(AtomicBool::new(false));
        let response_dropped = Arc::new(AtomicBool::new(false));
        let drop_claimed = Arc::new(AtomicBool::new(false));
        let connection_count = Arc::new(AtomicUsize::new(0));

        let thread_stop = stop.clone();
        let thread_dropped = response_dropped.clone();
        let thread_claimed = drop_claimed.clone();
        let thread_connections = connection_count.clone();
        let thread = thread::spawn(move || {
            let mut handlers = Vec::new();
            while !thread_stop.load(Ordering::Acquire) {
                match listener.accept() {
                    Ok((client, _)) => {
                        thread_connections.fetch_add(1, Ordering::AcqRel);
                        let handler_stop = thread_stop.clone();
                        let handler_dropped = thread_dropped.clone();
                        let handler_claimed = thread_claimed.clone();
                        handlers.push(thread::spawn(move || {
                            relay_connection(
                                client,
                                upstream_port,
                                request_marker,
                                handler_stop,
                                handler_claimed,
                                handler_dropped,
                                mode,
                            );
                        }));
                    }
                    Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(10));
                    }
                    Err(error) if error.kind() == std::io::ErrorKind::Interrupted => {}
                    Err(_) => break,
                }
            }
            for handler in handlers {
                let _ = handler.join();
            }
        });

        Self {
            port,
            stop,
            response_dropped,
            connection_count,
            thread: Some(thread),
        }
    }

    fn port(&self) -> u16 {
        self.port
    }

    fn wait(mut self) {
        self.stop.store(true, Ordering::Release);
        self.thread.take().unwrap().join().unwrap();
        assert!(
            self.response_dropped.load(Ordering::Acquire),
            "proxy did not observe and drop the targeted response"
        );
        assert!(
            self.connection_count.load(Ordering::Acquire) >= 2,
            "coordinator did not reconnect after the dropped response"
        );
    }
}

impl Drop for DropResponseProxy {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

fn relay_connection(
    client: StdTcpStream,
    upstream_port: u16,
    request_marker: &'static [u8],
    stop: Arc<AtomicBool>,
    drop_claimed: Arc<AtomicBool>,
    response_dropped: Arc<AtomicBool>,
    mode: DropResponseMode,
) {
    let upstream = match StdTcpStream::connect(("127.0.0.1", upstream_port)) {
        Ok(stream) => stream,
        Err(_) => return,
    };
    for stream in [&client, &upstream] {
        let _ = stream.set_nodelay(true);
        let _ = stream.set_read_timeout(Some(Duration::from_millis(200)));
        let _ = stream.set_write_timeout(Some(Duration::from_millis(200)));
    }

    let armed = Arc::new(AtomicBool::new(false));
    let mut client_reader = match client.try_clone() {
        Ok(stream) => stream,
        Err(_) => return,
    };
    let mut upstream_writer = match upstream.try_clone() {
        Ok(stream) => stream,
        Err(_) => return,
    };
    let forward_stop = stop.clone();
    let forward_armed = armed.clone();
    let forward_claimed = drop_claimed.clone();
    let forward = thread::spawn(move || {
        let mut buffer = [0_u8; 16 * 1024];
        let mut tail = Vec::new();
        while !forward_stop.load(Ordering::Acquire) {
            let read = match client_reader.read(&mut buffer) {
                Ok(0) => break,
                Ok(read) => read,
                Err(error)
                    if matches!(
                        error.kind(),
                        std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
                    ) =>
                {
                    continue;
                }
                Err(_) => break,
            };
            let mut observed = Vec::with_capacity(tail.len() + read);
            observed.extend_from_slice(&tail);
            observed.extend_from_slice(&buffer[..read]);
            if !forward_claimed.load(Ordering::Acquire)
                && observed
                    .windows(request_marker.len())
                    .any(|window| window == request_marker)
                && forward_claimed
                    .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
                    .is_ok()
            {
                forward_armed.store(true, Ordering::Release);
            }
            let keep = request_marker.len().saturating_sub(1).min(observed.len());
            tail.clear();
            tail.extend_from_slice(&observed[observed.len() - keep..]);
            if upstream_writer.write_all(&buffer[..read]).is_err() {
                break;
            }
        }
        let _ = upstream_writer.shutdown(std::net::Shutdown::Write);
    });

    let mut upstream_reader = upstream;
    let mut client_writer = client;
    let mut buffer = [0_u8; 16 * 1024];
    let mut held_postgres_frames = Vec::new();
    let mut postgres_ready_count = 0_usize;
    'responses: while !stop.load(Ordering::Acquire) {
        let read = match upstream_reader.read(&mut buffer) {
            Ok(0) => break,
            Ok(read) => read,
            Err(error)
                if matches!(
                    error.kind(),
                    std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
                ) =>
            {
                continue;
            }
            Err(_) => break,
        };
        if armed.load(Ordering::Acquire) {
            match mode {
                DropResponseMode::FirstResponse => {
                    response_dropped.store(true, Ordering::Release);
                    let _ = client_writer.shutdown(std::net::Shutdown::Both);
                    let _ = upstream_reader.shutdown(std::net::Shutdown::Both);
                    break;
                }
                DropResponseMode::PostgresReadyForQuery => {
                    held_postgres_frames.extend_from_slice(&buffer[..read]);
                    assert!(
                        held_postgres_frames.len() <= 1024 * 1024,
                        "PostgreSQL fault-injection response exceeded its bound"
                    );
                    let mut consumed = 0_usize;
                    while held_postgres_frames.len().saturating_sub(consumed) >= 5 {
                        let length = u32::from_be_bytes(
                            held_postgres_frames[consumed + 1..consumed + 5]
                                .try_into()
                                .unwrap(),
                        ) as usize;
                        assert!(length >= 4, "invalid PostgreSQL response frame length");
                        let frame_length = 1 + length;
                        if held_postgres_frames.len() - consumed < frame_length {
                            break;
                        }
                        let message_type = held_postgres_frames[consumed];
                        consumed += frame_length;
                        if message_type == b'Z' {
                            postgres_ready_count += 1;
                            if postgres_ready_count == 1 {
                                if client_writer
                                    .write_all(&held_postgres_frames[..consumed])
                                    .is_err()
                                {
                                    break 'responses;
                                }
                                held_postgres_frames.drain(..consumed);
                                break;
                            }
                            response_dropped.store(true, Ordering::Release);
                            let _ = client_writer.shutdown(std::net::Shutdown::Both);
                            let _ = upstream_reader.shutdown(std::net::Shutdown::Both);
                            break 'responses;
                        }
                    }
                    continue;
                }
            }
        }
        if client_writer.write_all(&buffer[..read]).is_err() {
            break;
        }
    }
    let _ = client_writer.shutdown(std::net::Shutdown::Both);
    let _ = upstream_reader.shutdown(std::net::Shutdown::Both);
    let _ = forward.join();
}

